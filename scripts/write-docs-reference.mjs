#!/usr/bin/env node
// Writes docs/reference/decision-points.md and docs/reference/features.md from the judgment kernel's manifest
// (packages/kyrn-judge/manifest.json), the same file the desktop app's settings read. Run it after the manifest
// changes: node scripts/write-docs-reference.mjs (or --check to fail when the pages are out of date).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "packages/kyrn-judge/manifest.json"), "utf8"));
const en = (text) => (typeof text === "string" ? text : (text?.en ?? ""));
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\n/g, " ");
const GENERATED = "<!-- Generated by scripts/write-docs-reference.mjs from packages/kyrn-judge/manifest.json. Do not edit by hand. -->";

function value(option, raw) {
	if (Array.isArray(raw)) return raw.length === 0 ? "none" : raw.map((item) => `\`${item}\``).join(", ");
	if (raw === "") return "empty";
	if (option.kind === "choice") return `\`${raw}\``;
	const unit = option.unit ? ` ${en(option.unit)}` : "";
	return `\`${raw}\`${unit}`;
}

function decisionPoints() {
	const lines = [
		GENERATED,
		"",
		"# Decision points",
		"",
		`Every decision point mu has, ${manifest.decisions.length} in all, grouped as the desktop app's settings group them. Each is asked as a short question about a small state; [How mu works](../architecture.md) explains the engine and [Judges](../judges.md) who answers.`,
		"",
		"Each point has a mode:",
		"",
		...manifest.modes.map((mode) => `- \`${mode.value}\`: ${en(mode.help)}`),
		"",
		"A fresh install runs every point in `shadow` (`\"modes\": { \"default\": \"shadow\" }` is the built-in default). Set `\"default\": \"active\"` in `~/.mu/agent/mu.json`, or a point's mode in the desktop app's settings, to let verdicts take effect; `/mu mode <point|default> <off|shadow|active>` switches one for the current session. See [Configuration](../configuration.md).",
		"",
		"The feature column names the switch in `features` that turns the whole behaviour off; its options are in [Features](features.md).",
		"",
	];
	for (const [group, title] of Object.entries(manifest.groups)) {
		const decisions = manifest.decisions.filter((decision) => decision.group === group);
		if (decisions.length === 0) continue;
		lines.push(`## ${en(title)}`, "", "| Decision point | Name | What it decides | Feature |", "| --- | --- | --- | --- |");
		for (const decision of decisions) {
			lines.push(
				`| \`${decision.id}\` | ${cell(en(decision.title))} | ${cell(en(decision.summary))} | [\`${decision.feature}\`](features.md#${decision.feature.toLowerCase()}) |`,
			);
		}
		lines.push("");
	}
	return lines.join("\n");
}

function features() {
	const lines = [
		GENERATED,
		"",
		"# Features",
		"",
		"Each feature is configured under `features.<name>` in `~/.mu/agent/mu.json`. `false` turns a feature off, `true` turns it on with its defaults, and an object overrides single options:",
		"",
		"```json",
		"{",
		'  "features": {',
		'    "injection": { "tools": ["web_fetch", "mcp__*"] },',
		'    "board": { "defaultOn": true },',
		'    "ttsr": false',
		"  }",
		"}",
		"```",
		"",
		"The desktop app's settings write the same file. Decision points that belong to a feature are listed in [Decision points](decision-points.md).",
		"",
	];
	for (const feature of manifest.features) {
		const decisions = manifest.decisions.filter((decision) => decision.feature === feature.name);
		lines.push(`## ${feature.name}`, "", `**${en(feature.title)}.** ${en(feature.summary)}`, "");
		lines.push(`On by default: ${feature.defaultEnabled ? "yes" : "no"}.${decisions.length > 0 ? ` Decision points: ${decisions.map((decision) => `\`${decision.id}\``).join(", ")}.` : ""}`, "");
		const options = feature.options ?? [];
		if (options.length > 0) {
			lines.push("| Option | Default | Meaning |", "| --- | --- | --- |");
			for (const option of options) {
				const range = option.min !== undefined && option.max !== undefined ? ` Range ${option.min} to ${option.max}.` : "";
				const choices = option.choices ? ` One of ${option.choices.map((choice) => `\`${choice.value}\` (${en(choice.label)})`).join(", ")}.` : "";
				const help = option.help ? ` ${en(option.help)}` : "";
				lines.push(`| \`${option.key}\` | ${value(option, option.default)} | ${cell(`${en(option.label)}.${help}${range}${choices}`.replace(/\.\./g, "."))} |`);
			}
			lines.push("");
		}
	}
	return lines.join("\n");
}

const pages = { "docs/reference/decision-points.md": decisionPoints(), "docs/reference/features.md": features() };
const check = process.argv.includes("--check");
let stale = false;
for (const [path, text] of Object.entries(pages)) {
	const file = join(root, path);
	if (check) {
		let current = "";
		try {
			current = readFileSync(file, "utf8");
		} catch {}
		if (current !== text) {
			console.error(`${path} is out of date: run node scripts/write-docs-reference.mjs`);
			stale = true;
		}
	} else writeFileSync(file, text);
}
if (stale) process.exit(1);
